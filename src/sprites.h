static inline u64 palette_color(unsigned char idx, int shade_pct) {
    int r = 0, g = 0, b = 0;
    switch (idx) {
        case 1:  r = 248; g = 204; b = 166; break;
        case 2:  r = 68;  g = 40;  b = 24;  break;
        case 3:  r = 28;  g = 175; b = 60;  break;
        case 4:  r = 36;  g = 80;  b = 210; break;
        case 5:  r = 18;  g = 18;  b = 22;  break;
        case 6:  r = 245; g = 245; b = 245; break;
        case 7:  r = 215; g = 35;  b = 35;  break;
        case 8:  r = 242; g = 210; b = 35;  break;
        case 9:  r = 120; g = 125; b = 135; break;
        case 10: r = 235; g = 110; b = 25;  break;
        default: return 0;
    }
    r = (r * shade_pct) / 100;
    g = (g * shade_pct) / 100;
    b = (b * shade_pct) / 100;
    return GS_SETREG_RGBAQ(r, g, b, 0x80, 0x00);
}

