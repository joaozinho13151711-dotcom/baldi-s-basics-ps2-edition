static inline void draw_pixel_art_2d(GSGLOBAL *gs, int x, int y, int pix_size, const unsigned char grid[12][12]) {
    for (int r = 0; r < 12; r++) {
        for (int c = 0; c < 12; c++) {
            unsigned char idx = grid[r][c];
            if (idx != 0) {
                gsKit_prim_sprite(gs,
                    x + c * pix_size, y + r * pix_size,
                    x + (c + 1) * pix_size, y + (r + 1) * pix_size,
                    8, palette_color(idx, 100));
            }
        }
    }
}

